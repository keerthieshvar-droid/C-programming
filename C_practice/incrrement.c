#include <stdio.h>
int main()
{
    int a = 5;

    printf("Initial a = %d\n\n", a);

     printf("Output of a++ : %d\n", a++);
     printf("Value of a now : %d\n",a);

     printf("Output of ++a : %d\n" , ++a);
     printf("Value of a now : %d\n" , a);

     printf("Output of a-- : %d\n" , a--);
     printf("Value of a now :%d\n" , a);

     printf("Output of --a : %d\n" , --a);
     printf("Value of a now : %d\n" , a);

return 0 ;
}
