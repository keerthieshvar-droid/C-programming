#include <stdio.h>
int main(){

           int a = 20 , b = 27;

           printf("Initial value of a = %d\n" , a);
           printf("Initial value of b = %d\n" , b);

          printf("Pre-increment (++a) = %d\n" , ++a);
          printf("Value of after pre-increment = %d\n" , a);

          printf("Post-increment (a++) = %d\n" , b++);
          printf("Value of after post-increment = %d\n" , b);

      return 0;
} 
